import { NextResponse } from "next/server";
import { getViewer } from "@/lib/server/auth";
import { isUuid } from "@/lib/report-contract";
import { validateEvidenceBytes, MAX_EVIDENCE_BYTES } from "@/lib/evidence-contract";
import { canViewReportEvidence, listReadyEvidence, reporterOwnsReport, saveEvidence } from "@/lib/server/evidence";
import { errorResponse, noStore } from "@/lib/server/responses";

const permittedReaders = ["reporter", "monitor", "coordinator", "admin"] as const;

/** List ready evidence metadata only for reports the caller may inspect. */
export async function GET(req: Request, ctx: { params: Promise<{ reportId: string }> }) {
  try {
    const viewer = await getViewer(req, [...permittedReaders]);
    const { reportId } = await ctx.params;
    if (!isUuid(reportId)) return inputError("Invalid report ID");
    if (!(await canViewReportEvidence(reportId, viewer))) return notFound("Report not found");
    return NextResponse.json({ evidence: await listReadyEvidence(reportId) }, { headers: noStore });
  } catch (error) {
    return errorResponse(error);
  }
}

/**
 * Multipart upload. Idempotency-Key is a client-generated UUID; storage paths
 * are generated by the server and never returned to callers.
 */
export async function POST(req: Request, ctx: { params: Promise<{ reportId: string }> }) {
  try {
    const viewer = await getViewer(req, ["reporter"]);
    const { reportId } = await ctx.params;
    if (!isUuid(reportId)) return inputError("Invalid report ID");
    if (!(await reporterOwnsReport(reportId, viewer.userId))) return notFound("Report not found");
    if (!req.headers.get("content-type")?.toLowerCase().startsWith("multipart/form-data"))
      return NextResponse.json({ error: { code: "CONTENT_TYPE", message: "Use multipart/form-data" } }, { status: 415, headers: noStore });
    const contentLength = Number(req.headers.get("content-length"));
    // Bound multipart overhead as well as the file itself before parsing the body.
    if (Number.isFinite(contentLength) && contentLength > MAX_EVIDENCE_BYTES + 64 * 1024)
      return NextResponse.json({ error: { code: "TOO_LARGE", message: "Evidence images cannot exceed 5 MB" } }, { status: 413, headers: noStore });

    const evidenceId = req.headers.get("idempotency-key") || "";
    if (!isUuid(evidenceId)) return inputError("Idempotency-Key must be a UUID");
    const form = await req.formData().catch(() => null);
    const file = form?.get("file");
    if (!(file instanceof File)) return inputError("Attach one image in the file field");
    if (file.size > MAX_EVIDENCE_BYTES)
      return NextResponse.json({ error: { code: "TOO_LARGE", message: "Evidence images cannot exceed 5 MB" } }, { status: 413, headers: noStore });

    const bytes = new Uint8Array(await file.arrayBuffer());
    let mimeType;
    try {
      mimeType = validateEvidenceBytes(file.type, bytes);
    } catch {
      return NextResponse.json({ error: { code: "UNSUPPORTED_MEDIA", message: "Evidence must be a valid JPEG, PNG, or WebP image" } }, { status: 415, headers: noStore });
    }

    const result = await saveEvidence({ req, evidenceId: evidenceId.toLowerCase(), reportId, reporterId: viewer.userId, mimeType, bytes });
    return NextResponse.json(
      { evidence: result.item, duplicate: result.duplicate, integrityNote: "SHA-256 identifies received bytes; it does not prove authenticity." },
      { status: result.duplicate ? 200 : 201, headers: noStore },
    );
  } catch (error) {
    if (error instanceof Error && error.message === "EVIDENCE_ID_CONFLICT")
      return NextResponse.json({ error: { code: "CONFLICT", message: "This evidence ID is already used for a different upload" } }, { status: 409, headers: noStore });
    return errorResponse(error);
  }
}

function inputError(message: string) {
  return NextResponse.json({ error: { code: "INPUT", message } }, { status: 400, headers: noStore });
}

function notFound(message: string) {
  return NextResponse.json({ error: { code: "NOT_FOUND", message } }, { status: 404, headers: noStore });
}
